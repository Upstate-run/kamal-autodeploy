// Package generate renders the deploy workflow from the config. The output is ordinary,
// editable GitHub Actions YAML; a header records a checksum so the generator can tell its
// own unmodified output from a file a person has edited (which it never overwrites).
package generate

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"sort"
	"strings"

	"github.com/Upstate-run/kamal-autodeploy/internal/config"
)

// Pinned actions and tools. Each is a full commit SHA of a release at least two weeks old
// when this version of the generator was cut; the comment names the release.
const (
	CheckoutAction  = "actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1"
	SetupGoAction   = "actions/setup-go@b7ad1dad31e06c5925ef5d2fc7ad053ef454303e # v7.0.0"
	SetupRubyAction = "ruby/setup-ruby@651ff0d62c5c79bed6d53ec518387aae20e72c1a # v1.329.0"
	GoVersion       = "1.27.3"
	GemRubyVersion  = "3.4"
	ModulePath      = "github.com/Upstate-run/kamal-autodeploy/cmd/kamal-autodeploy"
	Runner          = "ubuntu-24.04"
)

// Names of the per-environment secret and variable the workflow reads for SSH.
const (
	SSHKeySecret      = "KAMAL_AUTODEPLOY_SSH_KEY"
	KnownHostsVar     = "KAMAL_AUTODEPLOY_KNOWN_HOSTS"
	UpstateToken      = "UPSTATE_HOOK_TOKEN"
	UpstateEnvVar     = "UPSTATE_HOOK_ENVIRONMENT"
	UpstateURLVar     = "UPSTATE_URL"
	ConcurrencyPrefix = "kamal-autodeploy"
)

const (
	markerLine   = "# Generated by kamal-autodeploy from .kamal-autodeploy.yml."
	checksumHead = "# kamal-autodeploy-checksum: sha256:"
)

// OutputKey turns a unit ID into a step-output and expression-safe key.
func OutputKey(id string) string { return strings.ReplaceAll(id, "-", "_") }

// Workflow renders the complete workflow file.
func Workflow(c *config.Config) ([]byte, error) {
	if err := c.Validate(); err != nil {
		return nil, err
	}
	body := render(c)
	sum := sha256.Sum256([]byte(body))
	header := markerLine + "\n" +
		"# Edit .kamal-autodeploy.yml and run `kamal-autodeploy init` to regenerate. If you edit this\n" +
		"# file by hand, the generator stops overwriting it (the checksum below no longer matches).\n" +
		checksumHead + hex.EncodeToString(sum[:]) + "\n"
	return []byte(header + body), nil
}

// State of an existing workflow file.
const (
	Absent     = "absent"
	Current    = "current"     // identical to what would be generated
	Outdated   = "outdated"    // our unmodified output from an older config: safe to replace
	HandEdited = "hand-edited" // carries our marker but was edited: never overwritten
	Foreign    = "foreign"     // not generated by this tool: never overwritten
)

// Classify compares an existing file with the newly generated content.
func Classify(existing, generated []byte) string {
	if existing == nil {
		return Absent
	}
	if string(existing) == string(generated) {
		return Current
	}
	s := string(existing)
	if !strings.HasPrefix(s, markerLine+"\n") {
		return Foreign
	}
	lines := strings.SplitN(s, "\n", 5)
	if len(lines) < 5 || !strings.HasPrefix(lines[3], checksumHead) {
		return HandEdited
	}
	sum := sha256.Sum256([]byte(lines[4]))
	if strings.TrimPrefix(lines[3], checksumHead) != hex.EncodeToString(sum[:]) {
		return HandEdited
	}
	return Outdated
}

type writer struct{ b strings.Builder }

func (w *writer) l(indent int, format string, args ...any) {
	w.b.WriteString(strings.Repeat(" ", indent))
	fmt.Fprintf(&w.b, format, args...)
	w.b.WriteString("\n")
}

func quote(s string) string {
	return `"` + strings.ReplaceAll(strings.ReplaceAll(s, `\`, `\\`), `"`, `\"`) + `"`
}

func shellQuote(s string) string { return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'" }

// transitivePredecessors is every unit a unit's job must wait for.
func transitivePredecessors(c *config.Config, id string) []string {
	seen := map[string]bool{}
	var walk func(string)
	walk = func(x string) {
		for _, p := range c.Predecessors(x) {
			if !seen[p] {
				seen[p] = true
				walk(p)
			}
		}
	}
	walk(id)
	out := []string{}
	for p := range seen {
		out = append(out, p)
	}
	sort.Strings(out)
	return out
}

func render(c *config.Config) string {
	w := &writer{}
	order, _ := c.Order()
	ids := []string{}
	for _, u := range c.Units {
		ids = append(ids, u.ID)
	}
	required := c.RequiredWorkflows()

	w.l(0, "name: %s", config.WorkflowName)
	w.l(0, "")
	w.l(0, "on:")
	w.l(2, "# Deploys follow CI on the trusted branch; a green pull request check is never enough.")
	w.l(2, "workflow_run:")
	names := []string{}
	for _, r := range required {
		names = append(names, quote(r))
	}
	w.l(4, "workflows: [%s]", strings.Join(names, ", "))
	w.l(4, "types: [completed]")
	w.l(4, "branches: [%s]", quote(c.Branch))
	w.l(2, "workflow_dispatch:")
	w.l(4, "inputs:")
	w.l(6, "action:")
	w.l(8, "description: \"deploy: deploy the unit now; rollback: roll the unit back to version; doctor: SSH check only\"")
	w.l(8, "type: choice")
	w.l(8, "options: [deploy, rollback, doctor]")
	w.l(8, "default: deploy")
	w.l(6, "unit:")
	w.l(8, "description: Deployment unit")
	w.l(8, "type: choice")
	w.l(8, "options: [%s]", strings.Join(ids, ", "))
	w.l(6, "version:")
	w.l(8, "description: Version to roll back to (rollback only; usually a full commit SHA)")
	w.l(8, "type: string")
	w.l(8, "required: false")
	w.l(0, "")
	w.l(0, "permissions: {}")
	w.l(0, "")
	w.l(0, "# One deploy run at a time per repository. A newer run waits; a still-queued older run may")
	w.l(0, "# be replaced, which is safe because selection always deploys the newest green commit")
	w.l(0, "# measured from each unit's last successful deploy.")
	w.l(0, "concurrency:")
	trustedWorkflows := []string{}
	for _, name := range required {
		wf, _ := c.Workflow(name)
		trustedWorkflows = append(trustedWorkflows, fmt.Sprintf("(github.event.workflow_run.name == '%s' && (github.event.workflow_run.path == '%s' || startsWith(github.event.workflow_run.path, '%s@')))", wf.Name, wf.Path, wf.Path))
	}
	group := fmt.Sprintf("%s-${{ github.event_name == 'workflow_dispatch' && github.ref == 'refs/heads/%s' && inputs.action != 'doctor' && 'trusted' || (github.event.workflow_run.event == 'push' && github.event.workflow_run.repository.full_name == github.repository && github.event.workflow_run.head_repository.full_name == github.repository && github.event.workflow_run.head_branch == '%s' && (%s) && 'trusted' || github.run_id) }}", ConcurrencyPrefix, c.Branch, c.Branch, strings.Join(trustedWorkflows, " || "))
	w.l(2, "group: %s", quote(group))
	w.l(2, "cancel-in-progress: false")
	w.l(0, "")
	w.l(0, "jobs:")

	// ---- select -------------------------------------------------------------------
	w.l(2, "select:")
	w.l(4, "name: Select units")
	w.l(4, "runs-on: %s", Runner)
	w.l(4, "timeout-minutes: 10")
	w.l(4, "permissions:")
	w.l(6, "contents: read")
	w.l(6, "actions: read")
	w.l(6, "deployments: read")
	w.l(4, "outputs:")
	w.l(6, "attention: ${{ steps.select.outputs.attention }}")
	for _, id := range ids {
		k := OutputKey(id)
		for _, f := range []string{"action", "sha", "baseline", "version", "automatic_head"} {
			w.l(6, "%s_%s: ${{ steps.select.outputs.%s_%s }}", k, f, k, f)
		}
	}
	w.l(4, "steps:")
	w.l(6, "- name: Verify the trigger before anything else")
	w.l(8, "id: verify")
	w.l(8, "env:")
	w.l(10, "EVENT_NAME: ${{ github.event_name }}")
	w.l(10, "REPO: ${{ github.repository }}")
	w.l(10, "REF: ${{ github.ref }}")
	w.l(10, "DISPATCH_SHA: ${{ github.sha }}")
	w.l(10, "RUN_REPO: ${{ github.event.workflow_run.repository.full_name }}")
	w.l(10, "RUN_HEAD_REPO: ${{ github.event.workflow_run.head_repository.full_name }}")
	w.l(10, "RUN_EVENT: ${{ github.event.workflow_run.event }}")
	w.l(10, "RUN_BRANCH: ${{ github.event.workflow_run.head_branch }}")
	w.l(10, "RUN_NAME: ${{ github.event.workflow_run.name }}")
	w.l(10, "RUN_PATH: ${{ github.event.workflow_run.path }}")
	w.l(10, "RUN_SHA: ${{ github.event.workflow_run.head_sha }}")
	w.l(8, "run: |")
	pairs := []string{}
	for _, r := range required {
		wf, _ := c.Workflow(r)
		pairs = append(pairs, quote(wf.Name+"|"+wf.Path))
	}
	script := []string{
		`set -euo pipefail`,
		`fail() { echo "::error::$1"; exit 1; }`,
		`case "$EVENT_NAME" in`,
		`  workflow_run)`,
		`    [ "$RUN_REPO" = "$REPO" ] || fail "CI run belongs to another repository"`,
		`    [ "$RUN_HEAD_REPO" = "$REPO" ] || fail "CI run was for a fork"`,
		`    [ "$RUN_EVENT" = "push" ] || fail "CI run was not a push"`,
		`    [ "$RUN_BRANCH" = ` + quote(c.Branch) + ` ] || fail "CI run was not on ` + c.Branch + `"`,
		`    case "$RUN_NAME|${RUN_PATH%%@*}" in`,
		`      ` + strings.Join(pairs, "|") + `) ;;`,
		`      *) fail "unexpected CI workflow" ;;`,
		`    esac`,
		`    sha="$RUN_SHA" ;;`,
		`  workflow_dispatch)`,
		`    [ "$REF" = ` + quote("refs/heads/"+c.Branch) + ` ] || fail "dispatch must run on ` + c.Branch + `"`,
		`    sha="$DISPATCH_SHA" ;;`,
		`  *) fail "unsupported event" ;;`,
		`esac`,
		`[[ "$sha" =~ ^[0-9a-f]{40}$ ]] || fail "invalid commit SHA"`,
		`echo "sha=$sha" >> "$GITHUB_OUTPUT"`,
	}
	for _, s := range script {
		w.l(10, "%s", s)
	}
	w.l(6, "- name: Check out the deploy branch (history only; nothing from it runs here)")
	w.l(8, "uses: %s", CheckoutAction)
	w.l(8, "with:")
	w.l(10, "ref: ${{ github.sha }}")
	w.l(10, "fetch-depth: 0")
	w.l(10, "persist-credentials: false")
	installTool(w, c)
	w.l(6, "- name: Select units")
	w.l(8, "id: select")
	w.l(8, "env:")
	w.l(10, "GITHUB_TOKEN: ${{ github.token }}")
	w.l(10, "EVENT_NAME: ${{ github.event_name }}")
	w.l(10, "TRIGGER_SHA: ${{ steps.verify.outputs.sha }}")
	w.l(10, "INPUT_ACTION: ${{ inputs.action }}")
	w.l(10, "INPUT_UNIT: ${{ inputs.unit }}")
	w.l(10, "INPUT_VERSION: ${{ inputs.version }}")
	w.l(8, `run: kamal-autodeploy select --event "$EVENT_NAME" --sha "$TRIGGER_SHA" --action "$INPUT_ACTION" --unit "$INPUT_UNIT" --version "$INPUT_VERSION"`)
	w.l(0, "")

	// ---- one deploy job per unit ---------------------------------------------------
	for _, id := range order {
		u, _ := c.Unit(id)
		renderUnit(w, c, u)
	}

	// ---- report ----------------------------------------------------------------------
	w.l(2, "report:")
	w.l(4, "name: Needs attention")
	needs := []string{"select"}
	for _, id := range order {
		needs = append(needs, "deploy-"+id)
	}
	w.l(4, "needs: [%s]", strings.Join(needs, ", "))
	w.l(4, "if: ${{ always() && needs.select.outputs.attention != '' }}")
	w.l(4, "runs-on: %s", Runner)
	w.l(4, "timeout-minutes: 5")
	w.l(4, "permissions: {}")
	w.l(4, "steps:")
	w.l(6, "- name: Fail the run so a person looks")
	w.l(8, "env:")
	w.l(10, "ATTENTION: ${{ needs.select.outputs.attention }}")
	w.l(8, `run: |`)
	w.l(10, `echo "::error::$ATTENTION"`)
	w.l(10, `exit 1`)
	return w.b.String()
}

func installTool(w *writer, c *config.Config) {
	w.l(6, "- name: Set up Go (to build the pinned kamal-autodeploy)")
	w.l(8, "uses: %s", SetupGoAction)
	w.l(8, "with:")
	w.l(10, "go-version: %s", quote(GoVersion))
	w.l(10, "cache: false")
	w.l(6, "- name: Install kamal-autodeploy %s (checksum-verified by the Go module proxy and sum database)", c.ToolVersion)
	w.l(8, "env:")
	w.l(10, "GOFLAGS: -mod=mod")
	w.l(10, "GOTOOLCHAIN: local")
	w.l(8, "run: |")
	w.l(10, "go install %s@%s", ModulePath, c.ToolVersion)
	w.l(10, `echo "$(go env GOPATH)/bin" >> "$GITHUB_PATH"`)
}

func renderUnit(w *writer, c *config.Config, u config.Unit) {
	k := OutputKey(u.ID)
	preds := transitivePredecessors(c, u.ID)
	needs := append([]string{"select"}, prefixAll("deploy-", preds)...)
	cond := []string{"!cancelled()", "needs.select.result == 'success'", fmt.Sprintf("needs.select.outputs.%s_action != ''", k), fmt.Sprintf("needs.select.outputs.%s_action != 'skip'", k)}
	for _, p := range preds {
		pk := OutputKey(p)
		cond = append(cond, fmt.Sprintf("(needs.deploy-%s.result == 'success' || (needs.deploy-%s.result == 'skipped' && needs.select.outputs.%s_action == 'skip'))", p, p, pk))
	}
	w.l(2, "deploy-%s:", u.ID)
	w.l(4, "name: Deploy %s", u.ID)
	w.l(4, "needs: [%s]", strings.Join(needs, ", "))
	w.l(4, "if: ${{ %s }}", strings.Join(cond, " && "))
	w.l(4, "runs-on: %s", Runner)
	w.l(4, "timeout-minutes: 60")
	w.l(4, "environment: %s", u.Environment)
	w.l(4, "permissions:")
	w.l(6, "contents: read")
	w.l(6, "deployments: write")
	if u.RegistryPassword == config.RegistryGitHubToken {
		w.l(6, "packages: write")
	}
	w.l(4, "env:")
	w.l(6, "ACTION: ${{ needs.select.outputs.%s_action }}", k)
	w.l(6, "DEPLOY_SHA: ${{ needs.select.outputs.%s_sha }}", k)
	w.l(4, "steps:")
	w.l(6, "- name: Check out the exact commit")
	w.l(8, "uses: %s", CheckoutAction)
	w.l(8, "with:")
	w.l(10, "ref: ${{ needs.select.outputs.%s_sha }}", k)
	w.l(10, "persist-credentials: false")
	w.l(6, "- name: Verify the checkout")
	w.l(8, "run: |")
	w.l(10, `[[ "$DEPLOY_SHA" =~ ^[0-9a-f]{40}$ ]] || { echo "::error::invalid commit SHA"; exit 1; }`)
	w.l(10, `[ "$(git rev-parse HEAD)" = "$DEPLOY_SHA" ] || { echo "::error::checkout is not $DEPLOY_SHA"; exit 1; }`)
	installTool(w, c)
	w.l(6, "- name: Last check before deploying (staleness) and open a GitHub Deployment")
	w.l(8, "id: guard")
	w.l(8, "env:")
	w.l(10, "GITHUB_TOKEN: ${{ github.token }}")
	w.l(10, "AUTOMATIC_HEAD: ${{ needs.select.outputs.%s_automatic_head }}", k)
	w.l(10, "BASELINE: ${{ needs.select.outputs.%s_baseline }}", k)
	w.l(10, "ROLLBACK_VERSION: ${{ needs.select.outputs.%s_version }}", k)
	w.l(10, "RUN_URL: ${{ github.server_url }}/${{ github.repository }}/actions/runs/${{ github.run_id }}")
	w.l(8, `run: kamal-autodeploy guard --unit %s --environment %s --branch %s --action "$ACTION" --sha "$DEPLOY_SHA" --baseline "$BASELINE" --automatic-head "$AUTOMATIC_HEAD" --version "$ROLLBACK_VERSION" --run-url "$RUN_URL"`, u.ID, u.Environment, shellQuote(c.Branch))

	proceed := "steps.guard.outputs.proceed == 'true'"
	kamalRuns := proceed + " && (env.ACTION == 'deploy' || env.ACTION == 'rollback')"
	w.l(6, "- name: Set up Ruby and Kamal")
	w.l(8, "if: ${{ %s }}", kamalRuns)
	w.l(8, "uses: %s", SetupRubyAction)
	w.l(8, "with:")
	if u.Kamal == config.KamalBundler {
		w.l(10, "bundler-cache: true")
	} else {
		w.l(10, "ruby-version: %s", quote(GemRubyVersion))
		w.l(6, "- name: Install kamal %s", u.KamalVersion)
		w.l(8, "if: ${{ %s }}", kamalRuns)
		w.l(8, "run: gem install kamal -v %s --no-document", shellQuote(u.KamalVersion))
	}

	w.l(6, "- name: SSH with the dedicated CI key and pinned host keys")
	w.l(8, "if: ${{ %s }}", proceed)
	w.l(8, "env:")
	w.l(10, "SSH_KEY: ${{ secrets.%s }}", SSHKeySecret)
	w.l(10, "KNOWN_HOSTS: ${{ vars.%s }}", KnownHostsVar)
	w.l(8, "run: |")
	ssh := []string{
		`set -euo pipefail`,
		`[ -n "$SSH_KEY" ] || { echo "::error::secret ` + SSHKeySecret + ` is missing in environment ` + u.Environment + `; run kamal-autodeploy provision"; exit 1; }`,
		`[ -n "$KNOWN_HOSTS" ] || { echo "::error::variable ` + KnownHostsVar + ` is missing in environment ` + u.Environment + `; run kamal-autodeploy provision"; exit 1; }`,
		`install -d -m 700 ~/.ssh`,
		`printf '%s\n' "$KNOWN_HOSTS" > ~/.ssh/known_hosts`,
		`chmod 600 ~/.ssh/known_hosts`,
		`printf 'Host *\n  StrictHostKeyChecking yes\n  UserKnownHostsFile ~/.ssh/known_hosts\n  BatchMode yes\n' > ~/.ssh/config`,
		`chmod 600 ~/.ssh/config`,
	}
	for _, h := range u.SSH.Hosts {
		name := h
		if u.SSH.Port != 22 {
			name = fmt.Sprintf("[%s]:%d", h, u.SSH.Port)
		}
		ssh = append(ssh, fmt.Sprintf(`ssh-keygen -F %s -f ~/.ssh/known_hosts > /dev/null || { echo "::error::host key for %s is not pinned; run kamal-autodeploy provision"; exit 1; }`, shellQuote(name), name))
	}
	ssh = append(ssh,
		`eval "$(ssh-agent -s)" > /dev/null`,
		`printf '%s\n' "$SSH_KEY" | ssh-add - 2> /dev/null`,
		`echo "SSH_AUTH_SOCK=$SSH_AUTH_SOCK" >> "$GITHUB_ENV"`,
		`echo "SSH_AGENT_PID=$SSH_AGENT_PID" >> "$GITHUB_ENV"`,
	)
	for _, s := range ssh {
		w.l(10, "%s", s)
	}

	if u.WriteSecretsFile {
		w.l(6, "- name: Write %s (names only; values stay in environment secrets)", u.SecretsFile)
		w.l(8, "if: ${{ %s }}", kamalRuns)
		w.l(8, "env:")
		w.l(10, "SECRETS_FILE: %s", u.SecretsFile)
		w.l(8, "run: |")
		lines := []string{
			`set -euo pipefail`,
			`if git ls-files --error-unmatch -- "$SECRETS_FILE" > /dev/null 2>&1; then echo "::error::$SECRETS_FILE is tracked; refusing to overwrite it"; exit 1; fi`,
			`install -d -m 700 "$(dirname "$SECRETS_FILE")"`,
			`umask 077`,
			`: > "$SECRETS_FILE"`,
		}
		names := append([]string{}, u.Secrets...)
		if u.RegistryPassword == config.RegistryGitHubToken {
			names = append(names, "KAMAL_REGISTRY_PASSWORD")
		}
		sort.Strings(names)
		for _, n := range names {
			// A literal $NAME reference: Kamal resolves it from the step's environment.
			lines = append(lines, fmt.Sprintf(`echo "%s=\$%s" >> "$SECRETS_FILE"`, n, n))
		}
		lines = append(lines, `git check-ignore -q -- "$SECRETS_FILE" || echo "::warning::$SECRETS_FILE is not ignored by git; add it to .gitignore"`)
		for _, s := range lines {
			w.l(10, "%s", s)
		}
	}

	if c.Upstate != nil {
		w.l(6, "- name: Install upstate CLI %s for Upstate receipts (optional; skipped without the variable)", c.Upstate.CLIVersion)
		w.l(8, "if: ${{ %s && vars.%s != '' }}", kamalRuns, UpstateEnvVar)
		w.l(8, "env:")
		w.l(10, "UPSTATE_CLI_VERSION: %s", quote(c.Upstate.CLIVersion))
		w.l(10, "UPSTATE_CLI_SHA256: %s", c.Upstate.SHA256)
		w.l(8, "run: |")
		for _, s := range []string{
			`set -euo pipefail`,
			`archive="upstate_${UPSTATE_CLI_VERSION}_linux_amd64.tar.gz"`,
			`dir="$RUNNER_TEMP/upstate-cli"`,
			`mkdir -p "$dir"`,
			`curl --fail --silent --show-error --location --proto '=https' --tlsv1.2 --max-redirs 5 -o "$dir/$archive" "https://github.com/Upstate-run/cli-releases/releases/download/v${UPSTATE_CLI_VERSION}/${archive}"`,
			`echo "${UPSTATE_CLI_SHA256}  $dir/$archive" | sha256sum --check --strict -`,
			`tar -xzf "$dir/$archive" -C "$dir" upstate`,
			`echo "$dir" >> "$GITHUB_PATH"`,
		} {
			w.l(10, "%s", s)
		}
	}

	w.l(6, "- name: Verify selected checkout host pins")
	w.l(8, "if: ${{ %s }}", proceed)
	w.l(8, "env:")
	w.l(10, "KNOWN_HOSTS: ${{ vars.%s }}", KnownHostsVar)
	verifyArgs := ""
	for _, arg := range u.Args {
		verifyArgs += " " + shellQuote(arg)
	}
	w.l(8, "run: kamal-autodeploy verify-hosts --config %s --destination %s --command %s --%s", shellQuote(u.Config), shellQuote(u.Destination), shellQuote(u.Command), verifyArgs)

	w.l(6, "- name: Run Kamal (%s)", u.Command)
	w.l(8, "id: kamal")
	w.l(8, "if: ${{ %s }}", kamalRuns)
	w.l(8, "env:")
	w.l(10, "ROLLBACK_VERSION: ${{ needs.select.outputs.%s_version }}", k)
	if u.RegistryPassword == config.RegistryGitHubToken {
		w.l(10, "KAMAL_REGISTRY_PASSWORD: ${{ github.token }}")
	}
	for _, s := range u.Secrets {
		w.l(10, "%s: ${{ secrets.%s }}", s, s)
	}
	if c.Upstate != nil {
		w.l(10, "%s: ${{ secrets.%s }}", UpstateToken, UpstateToken)
		w.l(10, "%s: ${{ vars.%s }}", UpstateEnvVar, UpstateEnvVar)
		w.l(10, "%s: ${{ vars.%s }}", UpstateURLVar, UpstateURLVar)
	}
	args := ""
	for _, a := range u.Args {
		args += " " + shellQuote(a)
	}
	w.l(8, "run: |")
	w.l(10, "set -euo pipefail")
	w.l(10, `case "$ACTION" in`)
	w.l(12, `deploy) %s deploy%s --version="$DEPLOY_SHA" ;;`, shellQuote(u.Command), args)
	w.l(12, `rollback)`)
	w.l(14, `[[ "$ROLLBACK_VERSION" =~ ^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$ ]] || { echo "::error::invalid rollback version"; exit 1; }`)
	w.l(14, `%s rollback "$ROLLBACK_VERSION"%s ;;`, shellQuote(u.Command), args)
	w.l(12, `*) echo "::error::unknown action $ACTION"; exit 1 ;;`)
	w.l(10, `esac`)

	w.l(6, "- name: SSH connectivity check (doctor)")
	w.l(8, "if: ${{ %s && env.ACTION == 'doctor' }}", proceed)
	w.l(8, "run: |")
	w.l(10, "set -euo pipefail")
	for _, h := range u.SSH.Hosts {
		w.l(10, "ssh -o ConnectTimeout=15 -p %d %s true && echo %s", u.SSH.Port, shellQuote(u.SSH.User+"@"+h), shellQuote("reachable: "+u.SSH.User+"@"+h))
	}

	w.l(6, "- name: Record the outcome on the GitHub Deployment")
	w.l(8, "if: ${{ always() && steps.guard.outputs.deployment_id != '' }}")
	w.l(8, "env:")
	w.l(10, "GITHUB_TOKEN: ${{ github.token }}")
	w.l(10, "DEPLOYMENT_ID: ${{ steps.guard.outputs.deployment_id }}")
	w.l(10, "OUTCOME: ${{ steps.kamal.outcome }}")
	w.l(10, "RUN_URL: ${{ github.server_url }}/${{ github.repository }}/actions/runs/${{ github.run_id }}")
	w.l(8, `run: kamal-autodeploy record --deployment-id "$DEPLOYMENT_ID" --outcome "$OUTCOME" --run-url "$RUN_URL"`)

	w.l(6, "- name: Clean up")
	w.l(8, "if: ${{ always() }}")
	w.l(8, "run: |")
	w.l(10, `if [ -n "${SSH_AGENT_PID:-}" ]; then ssh-agent -k > /dev/null || true; fi`)
	w.l(10, "rm -f ~/.ssh/known_hosts ~/.ssh/config")
	if u.WriteSecretsFile {
		w.l(10, "rm -f %s", shellQuote(u.SecretsFile))
	}
	w.l(0, "")
}

func prefixAll(prefix string, xs []string) []string {
	out := []string{}
	for _, x := range xs {
		out = append(out, prefix+x)
	}
	return out
}
